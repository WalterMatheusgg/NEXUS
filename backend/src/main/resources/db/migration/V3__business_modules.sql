CREATE TABLE OPPORTUNITIES (
    ID NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ORGANIZATION_ID NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    VERSION NUMBER(19) DEFAULT 0 NOT NULL,
    TITLE VARCHAR2(200 CHAR) NOT NULL,
    CUSTOMER_ID NUMBER(19),
    LEAD_ID NUMBER(19),
    ASSIGNEE_ID NUMBER(19),
    STAGE VARCHAR2(20 CHAR) NOT NULL,
    AMOUNT NUMBER(17,2) DEFAULT 0 NOT NULL,
    PROBABILITY NUMBER(10) DEFAULT 0 NOT NULL,
    EXPECTED_CLOSE_DATE DATE,
    DESCRIPTION VARCHAR2(4000 CHAR),
    CONSTRAINT UK_OPP_ORG_ID UNIQUE (ORGANIZATION_ID, ID),
    CONSTRAINT FK_OPP_ORG FOREIGN KEY (ORGANIZATION_ID) REFERENCES ORGANIZATIONS(ID),
    CONSTRAINT CK_OPP_STAGE CHECK (STAGE IN ('NEW_LEAD', 'CONTACTED', 'QUALIFICATION', 'PROPOSAL', 'NEGOTIATION', 'WON', 'LOST')),
    CONSTRAINT CK_OPP_AMOUNT CHECK (AMOUNT>=0),
    CONSTRAINT CK_OPP_PROB CHECK (PROBABILITY BETWEEN 0 AND 100),
    CONSTRAINT CK_OPP_CLOSED CHECK ((STAGE='WON' AND PROBABILITY=100) OR (STAGE='LOST' AND PROBABILITY=0) OR STAGE NOT IN ('WON','LOST')),
    CONSTRAINT FK_OPP_CUST FOREIGN KEY (ORGANIZATION_ID, CUSTOMER_ID) REFERENCES CUSTOMERS(ORGANIZATION_ID, ID),
    CONSTRAINT FK_OPP_LEAD FOREIGN KEY (ORGANIZATION_ID, LEAD_ID) REFERENCES SALES_LEADS(ORGANIZATION_ID, ID),
    CONSTRAINT FK_OPP_ASSIGN FOREIGN KEY (ORGANIZATION_ID, ASSIGNEE_ID) REFERENCES APP_USERS(ORGANIZATION_ID, ID)
);
CREATE INDEX IX_OPP_CUST ON OPPORTUNITIES(ORGANIZATION_ID, CUSTOMER_ID);
CREATE INDEX IX_OPP_LEAD ON OPPORTUNITIES(ORGANIZATION_ID, LEAD_ID);
CREATE INDEX IX_OPP_ASSIGN ON OPPORTUNITIES(ORGANIZATION_ID, ASSIGNEE_ID);
