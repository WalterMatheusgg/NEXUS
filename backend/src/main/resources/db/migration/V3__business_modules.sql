-- Business data: all relationships include ORGANIZATION_ID to prevent cross-company references.
-- Versioned structure only; no demonstration customers, users or sales records.

CREATE TABLE CUSTOMERS (
    ID NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ORGANIZATION_ID NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    VERSION NUMBER(19) DEFAULT 0 NOT NULL,
    CUSTOMER_TYPE VARCHAR2(12 CHAR) NOT NULL,
    NAME VARCHAR2(160 CHAR) NOT NULL,
    DOCUMENT VARCHAR2(14 CHAR) NOT NULL,
    EMAIL VARCHAR2(254 CHAR),
    PHONE VARCHAR2(40 CHAR),
    ADDRESS VARCHAR2(1000 CHAR),
    ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT UK_CUST_ORG_ID UNIQUE (ORGANIZATION_ID, ID),
    CONSTRAINT FK_CUST_ORG FOREIGN KEY (ORGANIZATION_ID) REFERENCES ORGANIZATIONS(ID),
    CONSTRAINT UK_CUST_DOC UNIQUE (ORGANIZATION_ID,DOCUMENT),
    CONSTRAINT CK_CUST_CUSTOMER_TYPE CHECK (CUSTOMER_TYPE IN ('PERSON', 'COMPANY')),
    CONSTRAINT CK_CUST_ACTIVE CHECK (ACTIVE IN (0,1)),
    CONSTRAINT CK_CUST_DOCUMENT CHECK ((CUSTOMER_TYPE='PERSON' AND LENGTH(DOCUMENT)=11) OR (CUSTOMER_TYPE='COMPANY' AND LENGTH(DOCUMENT)=14))
);
CREATE INDEX IX_CUST_SEARCH ON CUSTOMERS(ORGANIZATION_ID,NAME);
CREATE INDEX IX_CUST_CREATED ON CUSTOMERS(ORGANIZATION_ID,CREATED_AT);

