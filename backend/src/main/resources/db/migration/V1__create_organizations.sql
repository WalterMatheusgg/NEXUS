CREATE TABLE ORGANIZATIONS (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CODE VARCHAR2(50 CHAR) NOT NULL,
    NAME VARCHAR2(160 CHAR) NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_ORGANIZATIONS_CODE UNIQUE (CODE),
    CONSTRAINT CK_ORGANIZATIONS_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE OR REPLACE TRIGGER TRG_ORGANIZATIONS_UPDATED_AT
BEFORE UPDATE ON ORGANIZATIONS
FOR EACH ROW
BEGIN
    :NEW.UPDATED_AT := SYSTIMESTAMP;
END;