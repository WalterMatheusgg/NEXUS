CREATE TABLE INSTALLATION_STATE (ID NUMBER(19) PRIMARY KEY, INITIALIZED NUMBER(1) DEFAULT 0 NOT NULL);
INSERT INTO INSTALLATION_STATE (ID, INITIALIZED) VALUES (1, 0);

CREATE TABLE APP_ROLES (
 ID NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 ORGANIZATION_ID NUMBER(19) NOT NULL REFERENCES ORGANIZATIONS(ID),
 CODE VARCHAR2(50 CHAR) NOT NULL, NAME VARCHAR2(100 CHAR) NOT NULL,
 PERMISSIONS VARCHAR2(2000 CHAR) DEFAULT 'DASHBOARD_READ' NOT NULL,
 CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, VERSION NUMBER(19) DEFAULT 0 NOT NULL,
 CONSTRAINT UK_ROLES_TENANT UNIQUE(ORGANIZATION_ID,ID), CONSTRAINT UK_ROLE_CODE UNIQUE(ORGANIZATION_ID,CODE)
);
CREATE TABLE DEPARTMENTS (
 ID NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 ORGANIZATION_ID NUMBER(19) NOT NULL REFERENCES ORGANIZATIONS(ID),
 NAME VARCHAR2(120 CHAR) NOT NULL, ACTIVE NUMBER(1) DEFAULT 1 NOT NULL CHECK(ACTIVE IN(0,1)),
 CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, VERSION NUMBER(19) DEFAULT 0 NOT NULL,
 CONSTRAINT UK_DEPT_TENANT UNIQUE(ORGANIZATION_ID,ID), CONSTRAINT UK_DEPT_NAME UNIQUE(ORGANIZATION_ID,NAME)
);
CREATE TABLE TEAMS (
 ID NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 ORGANIZATION_ID NUMBER(19) NOT NULL REFERENCES ORGANIZATIONS(ID),
 NAME VARCHAR2(120 CHAR) NOT NULL, DEPARTMENT_ID NUMBER(19), ACTIVE NUMBER(1) DEFAULT 1 NOT NULL CHECK(ACTIVE IN(0,1)),
 CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, VERSION NUMBER(19) DEFAULT 0 NOT NULL,
 CONSTRAINT UK_TEAM_TENANT UNIQUE(ORGANIZATION_ID,ID), CONSTRAINT UK_TEAM_NAME UNIQUE(ORGANIZATION_ID,NAME),
 CONSTRAINT FK_TEAM_DEPT FOREIGN KEY(ORGANIZATION_ID,DEPARTMENT_ID) REFERENCES DEPARTMENTS(ORGANIZATION_ID,ID)
);
CREATE INDEX IX_TEAM_DEPT ON TEAMS(ORGANIZATION_ID,DEPARTMENT_ID);
CREATE TABLE APP_USERS (
 ID NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 ORGANIZATION_ID NUMBER(19) NOT NULL REFERENCES ORGANIZATIONS(ID),
 NAME VARCHAR2(120 CHAR) NOT NULL, EMAIL VARCHAR2(254 CHAR) NOT NULL, PASSWORD_HASH VARCHAR2(255 CHAR) NOT NULL,
 ROLE_ID NUMBER(19) NOT NULL, DEPARTMENT_ID NUMBER(19), TEAM_ID NUMBER(19),
 ACTIVE NUMBER(1) DEFAULT 1 NOT NULL CHECK(ACTIVE IN(0,1)), FAILED_ATTEMPTS NUMBER(10) DEFAULT 0 NOT NULL,
 LOCKED_UNTIL TIMESTAMP WITH TIME ZONE, LAST_LOGIN_AT TIMESTAMP WITH TIME ZONE, AUTH_VERSION NUMBER(19) DEFAULT 0 NOT NULL,
 CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, VERSION NUMBER(19) DEFAULT 0 NOT NULL,
 CONSTRAINT UK_USER_TENANT UNIQUE(ORGANIZATION_ID,ID), CONSTRAINT UK_USER_EMAIL UNIQUE(ORGANIZATION_ID,EMAIL),
 CONSTRAINT CK_USER_EMAIL_CASE CHECK(EMAIL=LOWER(EMAIL)),
 CONSTRAINT FK_USER_ROLE FOREIGN KEY(ORGANIZATION_ID,ROLE_ID) REFERENCES APP_ROLES(ORGANIZATION_ID,ID),
 CONSTRAINT FK_USER_DEPT FOREIGN KEY(ORGANIZATION_ID,DEPARTMENT_ID) REFERENCES DEPARTMENTS(ORGANIZATION_ID,ID),
 CONSTRAINT FK_USER_TEAM FOREIGN KEY(ORGANIZATION_ID,TEAM_ID) REFERENCES TEAMS(ORGANIZATION_ID,ID)
);
CREATE INDEX IX_USER_ROLE ON APP_USERS(ORGANIZATION_ID,ROLE_ID);
CREATE INDEX IX_USER_DEPT ON APP_USERS(ORGANIZATION_ID,DEPARTMENT_ID);
CREATE INDEX IX_USER_TEAM ON APP_USERS(ORGANIZATION_ID,TEAM_ID);
CREATE TABLE PASSWORD_RESET_TOKENS (
 ID NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY, ORGANIZATION_ID NUMBER(19) NOT NULL REFERENCES ORGANIZATIONS(ID),
 USER_ID NUMBER(19) NOT NULL, TOKEN_HASH VARCHAR2(64 CHAR) NOT NULL UNIQUE,
 EXPIRES_AT TIMESTAMP WITH TIME ZONE NOT NULL, USED_AT TIMESTAMP WITH TIME ZONE,
 CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, VERSION NUMBER(19) DEFAULT 0 NOT NULL,
 CONSTRAINT FK_RESET_USER FOREIGN KEY(ORGANIZATION_ID,USER_ID) REFERENCES APP_USERS(ORGANIZATION_ID,ID)
);
CREATE INDEX IX_RESET_USER ON PASSWORD_RESET_TOKENS(ORGANIZATION_ID,USER_ID);
CREATE INDEX IX_RESET_EXPIRY ON PASSWORD_RESET_TOKENS(EXPIRES_AT);
CREATE TABLE AUDIT_EVENTS (
 ID NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY, ORGANIZATION_ID NUMBER(19) NOT NULL REFERENCES ORGANIZATIONS(ID),
 ACTOR_ID NUMBER(19), ACTOR_NAME VARCHAR2(120 CHAR) NOT NULL,
 ACTION VARCHAR2(80 CHAR) NOT NULL, ENTITY_TYPE VARCHAR2(80 CHAR) NOT NULL, ENTITY_ID NUMBER(19), DETAIL VARCHAR2(1000 CHAR),
 CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, VERSION NUMBER(19) DEFAULT 0 NOT NULL,
 CONSTRAINT FK_AUDIT_ACTOR FOREIGN KEY(ORGANIZATION_ID,ACTOR_ID) REFERENCES APP_USERS(ORGANIZATION_ID,ID)
);
CREATE INDEX IX_AUDIT_TENANT_DATE ON AUDIT_EVENTS(ORGANIZATION_ID,CREATED_AT);
CREATE INDEX IX_AUDIT_ACTOR ON AUDIT_EVENTS(ORGANIZATION_ID,ACTOR_ID);
CREATE TABLE NOTIFICATIONS (
 ID NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY, ORGANIZATION_ID NUMBER(19) NOT NULL REFERENCES ORGANIZATIONS(ID),
 USER_ID NUMBER(19) NOT NULL, TITLE VARCHAR2(160 CHAR) NOT NULL, MESSAGE VARCHAR2(1000 CHAR), LINK VARCHAR2(250 CHAR),
 IS_READ NUMBER(1) DEFAULT 0 NOT NULL CHECK(IS_READ IN(0,1)),
 CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, VERSION NUMBER(19) DEFAULT 0 NOT NULL,
 CONSTRAINT FK_NOTIFICATION_USER FOREIGN KEY(ORGANIZATION_ID,USER_ID) REFERENCES APP_USERS(ORGANIZATION_ID,ID)
);
CREATE INDEX IX_NOTIFICATION_USER ON NOTIFICATIONS(ORGANIZATION_ID,USER_ID,IS_READ,CREATED_AT);
CREATE TABLE MAIL_OUTBOX (
 ID NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY, ORGANIZATION_ID NUMBER(19) NOT NULL REFERENCES ORGANIZATIONS(ID),
 RECIPIENT VARCHAR2(254 CHAR) NOT NULL, SUBJECT VARCHAR2(160 CHAR) NOT NULL, BODY VARCHAR2(4000 CHAR) NOT NULL,
 ATTEMPTS NUMBER(10) DEFAULT 0 NOT NULL, SENT_AT TIMESTAMP WITH TIME ZONE, NEXT_ATTEMPT_AT TIMESTAMP WITH TIME ZONE,
 CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, VERSION NUMBER(19) DEFAULT 0 NOT NULL
);
CREATE INDEX IX_MAIL_PENDING ON MAIL_OUTBOX(SENT_AT,NEXT_ATTEMPT_AT);
